// Read the actual release modules. This smoke neither opens a browser nor starts any host.
import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import { modulesInOrder } from './build.mjs';

const fixture = JSON.parse(await readFile(new URL('fixtures/team.json', import.meta.url), 'utf8'));
const context = vm.createContext({ crypto: webcrypto, TextEncoder, Blob, atob, btoa, Uint8Array });
const { scripts } = await modulesInOrder();
for (const { name, code } of scripts) {
  if (name !== 'app.js') vm.runInContext(code, context, { filename: name });
}
const { TeamDefinition, NativeRoomExport, TeamBuilderAdapters, WorkBuddyExport, GrokPlan, DSPlanner } =
  vm.runInContext('({TeamDefinition, NativeRoomExport, TeamBuilderAdapters, WorkBuddyExport, GrokPlan, DSPlanner})', context);
const team = TeamDefinition.normalize(fixture);
const plain = value => JSON.parse(JSON.stringify(value));

// All ZIPs generated by this project use ZIP32 and stored entries with lengths in the local headers.
async function storedEntries(blob) {
  const bytes = Buffer.from(await blob.arrayBuffer());
  const entries = new Map();
  let at = 0;
  while (bytes.readUInt32LE(at) === 0x04034b50) {
    assert.equal(bytes.readUInt16LE(at + 8), 0, 'expected stored entries');
    const size = bytes.readUInt32LE(at + 18);
    const nameSize = bytes.readUInt16LE(at + 26);
    const extraSize = bytes.readUInt16LE(at + 28);
    const name = bytes.toString('utf8', at + 30, at + 30 + nameSize);
    const start = at + 30 + nameSize + extraSize;
    assert(start + size <= bytes.length && !entries.has(name));
    entries.set(name, bytes.subarray(start, start + size));
    at = start + size;
  }
  assert.equal(bytes.readUInt32LE(at), 0x02014b50, 'expected a central directory');
  return entries;
}

const room = { id: 'handoff', responder: { kind: 'agent', agent: 'keeper' } };
const department = JSON.parse(await (await NativeRoomExport.build(team, [room])).text()).package;
assert.deepEqual(department.agents.map(r => r.key), fixture.roles.map(r => r.id));
assert.deepEqual(department.rooms[0].members, fixture.groups[0].members);
assert.equal(department.rooms[0].defaultResponder.agent, 'keeper');
await assert.rejects(NativeRoomExport.build(team, [{ ...room, responder: { kind: 'agent', agent: 'reviewer' } }]));

const project = await storedEntries(await TeamBuilderAdapters.exportDeepSeekHarness(team));
assert.deepEqual(JSON.parse(project.get('team.definition.json')), fixture);
assert(project.has('.dsh/skills/solo-to-team/SKILL.md'));
const split = { ...fixture, workflow: { ...fixture.workflow, deliver: 'keeper' } };
assert.throws(() => TeamBuilderAdapters.exportDeepSeekHarness(split), /same root role/);

const work = await WorkBuddyExport.build(team);
const pluginFiles = await storedEntries(work.blob);
const manifestPath = [...pluginFiles.keys()].find(name => name.endsWith('/.codebuddy-plugin/plugin.json'));
const manifest = JSON.parse(pluginFiles.get(manifestPath));
assert.equal(manifest.expertType, 'team');
assert.equal(manifest.members.length, fixture.roles.length);
assert.equal([...pluginFiles.keys()].filter(name => name.includes('/agents/')).length, fixture.roles.length);
await assert.rejects(WorkBuddyExport.build(split), /split return/);

const guided = GrokPlan.rosterPlan(team, 'smoke');
assert.deepEqual(plain(guided.workflow), fixture.workflow);
assert.equal(guided.roles.length, fixture.roles.length);
assert(guided.groups.every(g => !g.native_group_requested));
assert.throws(() => GrokPlan.rosterPlan(team, '../collision'));

const nativeOptions = { handoff: { kind: 'native', admin: 'keeper', mode: 'admin' } };
const ds = await DSPlanner.build(team, { batch: 'smoke', groups: nativeOptions });
assert.equal(ds.plan.objects.find(o => o.kind === 'group' && o.id === 'handoff').create_group.admin, 'smoke·Stock keeper');
assert.equal(ds.plan.objects.find(o => o.kind === 'group' && o.id === 'quality').action, 'reference');
const collision = await DSPlanner.build(team, { batch: 'smoke', groups: nativeOptions, occupied: ['smoke·Producer'] });
const existing = collision.plan.objects.find(o => o.kind === 'bot' && o.id === 'maker');
assert.equal(existing.action, 'compare_existing');
assert.equal(existing.create_bot, null);
assert.deepEqual(plain(team), fixture);
console.log('PASS  one fictional team; OpenMaus department and rooms; DSH project ZIP; WorkBuddy ZIP; Grok and DS Bot plans; scope and collision checks');
